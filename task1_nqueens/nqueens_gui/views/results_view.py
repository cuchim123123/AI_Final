"""Tab 4: Saved Results & Plot Artifacts Browser."""
from __future__ import annotations

import os
from typing import List

import pandas as pd
from PySide6.QtCore import Qt
from PySide6.QtGui import QPixmap
from PySide6.QtWidgets import (
    QFileDialog,
    QGroupBox,
    QHBoxLayout,
    QHeaderView,
    QLabel,
    QListWidget,
    QListWidgetItem,
    QMessageBox,
    QPushButton,
    QScrollArea,
    QSplitter,
    QTabWidget,
    QTableWidget,
    QTableWidgetItem,
    QVBoxLayout,
    QWidget,
)


class ResultsView(QWidget):
    """Browse existing CSV results and PNG plot artifacts generated by experiments."""

    def __init__(self, parent=None) -> None:
        super().__init__(parent)
        self.results_dir = "results"
        self._init_ui()
        self.refresh_files()

    def _init_ui(self) -> None:
        main_layout = QHBoxLayout(self)
        main_layout.setContentsMargins(14, 14, 14, 14)
        main_layout.setSpacing(14)

        splitter = QSplitter(Qt.Horizontal)

        # -------------------- LEFT PANEL: FILE LIST --------------------
        left_widget = QWidget()
        left_layout = QVBoxLayout(left_widget)
        left_layout.setContentsMargins(0, 0, 0, 0)
        left_layout.setSpacing(8)

        file_group = QGroupBox("Generated Results")
        file_layout = QVBoxLayout(file_group)

        self.list_files = QListWidget()
        self.list_files.currentItemChanged.connect(self._on_file_selected)
        file_layout.addWidget(self.list_files)

        self.btn_refresh = QPushButton("🔄 Refresh Files")
        self.btn_refresh.clicked.connect(self.refresh_files)
        file_layout.addWidget(self.btn_refresh)

        left_layout.addWidget(file_group)
        left_widget.setMinimumWidth(260)
        left_widget.setMaximumWidth(320)
        splitter.addWidget(left_widget)

        # -------------------- RIGHT PANEL: CONTENT VIEWER --------------------
        self.tab_container = QTabWidget()

        # Tab 1: Table viewer
        self.table_view = QTableWidget()
        self.table_view.setAlternatingRowColors(True)
        self.tab_container.addTab(self.table_view, "📊 Data Table")

        # Tab 2: Matching Plot Images
        self.image_scroll = QScrollArea()
        self.image_scroll.setWidgetResizable(True)
        self.image_container = QWidget()
        self.image_layout = QVBoxLayout(self.image_container)
        self.image_scroll.setWidget(self.image_container)
        self.tab_container.addTab(self.image_scroll, "🖼️ Plot Figures")

        splitter.addWidget(self.tab_container)
        splitter.setStretchFactor(1, 3)
        main_layout.addWidget(splitter)

    def refresh_files(self) -> None:
        self.list_files.clear()
        if not os.path.exists(self.results_dir):
            return

        # Scan for CSV files in results/ and results/baseline_snapshot/
        for root, _, files in os.walk(self.results_dir):
            for f in sorted(files):
                if f.endswith(".csv"):
                    rel_path = os.path.relpath(os.path.join(root, f), self.results_dir)
                    item = QListWidgetItem(f"📄 {rel_path}")
                    item.setData(Qt.UserRole, os.path.join(root, f))
                    self.list_files.addItem(item)

        if self.list_files.count() > 0:
            self.list_files.setCurrentRow(0)

    def _on_file_selected(self, current: QListWidgetItem, previous: QListWidgetItem) -> None:
        if not current:
            return
        path = current.data(Qt.UserRole)
        if not path or not os.path.exists(path):
            return

        try:
            df = pd.read_csv(path)
            self._display_table(df)
            self._display_matching_plots(path)
        except Exception as e:
            QMessageBox.warning(self, "Read Error", f"Could not load '{path}':\n{e}")

    def _display_table(self, df: pd.DataFrame) -> None:
        self.table_view.clear()
        if df.empty:
            return
        self.table_view.setRowCount(len(df))
        self.table_view.setColumnCount(len(df.columns))
        self.table_view.setHorizontalHeaderLabels([str(c) for c in df.columns])

        for r_idx, (_, row) in enumerate(df.iterrows()):
            for c_idx, val in enumerate(row):
                if isinstance(val, float):
                    txt = f"{val:.5f}" if abs(val) < 1 else f"{val:.3f}"
                else:
                    txt = str(val)
                item = QTableWidgetItem(txt)
                item.setTextAlignment(Qt.AlignCenter)
                self.table_view.setItem(r_idx, c_idx, item)

        self.table_view.horizontalHeader().setSectionResizeMode(QHeaderView.ResizeToContents)

    def _display_matching_plots(self, csv_path: str) -> None:
        # Clear existing images
        while self.image_layout.count():
            child = self.image_layout.takeAt(0)
            if child.widget():
                child.widget().deleteLater()

        # Find prefix
        base_name = os.path.basename(csv_path)
        dir_name = os.path.dirname(csv_path)
        prefix = base_name.split("_")[0]  # e.g., 'sat', 'minconf', 'opt'

        found_plots = 0
        if os.path.exists(dir_name):
            for f in sorted(os.listdir(dir_name)):
                if f.endswith(".png") and f.startswith(prefix):
                    img_path = os.path.join(dir_name, f)
                    pixmap = QPixmap(img_path)
                    if not pixmap.isNull():
                        lbl_title = QLabel(f"<b>{f}</b>")
                        lbl_title.setStyleSheet("font-size: 13px; color: #212529; margin-top: 8px;")
                        lbl_img = QLabel()
                        lbl_img.setPixmap(pixmap.scaledToWidth(680, Qt.SmoothTransformation))
                        lbl_img.setAlignment(Qt.AlignCenter)

                        self.image_layout.addWidget(lbl_title)
                        self.image_layout.addWidget(lbl_img)
                        found_plots += 1

        if found_plots == 0:
            lbl_none = QLabel("No matching PNG plots found for this dataset.")
            lbl_none.setStyleSheet("color: #6C757D; font-style: italic; padding: 20px;")
            self.image_layout.addWidget(lbl_none)
